export const getCountryByName = (name) => {
  if (!name) return null;
  const lower = name.toLowerCase().trim();
  return (
    COUNTRIES.find(
      (c) =>
        c.name.toLowerCase() === lower ||
        c.geoName.toLowerCase() === lower ||
        c.code.toLowerCase() === lower
    ) || null
  );
};

export const isCountryMatch = (featName, country) => {
  if (!featName || !country) return false;
  const f = featName.toLowerCase();
  const n = country.name?.toLowerCase();
  const g = country.geoName?.toLowerCase();
  if (f === n || f === g) return true;
  if (g && (f.includes(g) || g.includes(f))) return true;
  if (n && (f.includes(n) || n.includes(f))) return true;
  return false;
};
